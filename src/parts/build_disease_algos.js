function generateAlgoHtml(id, algo) {
  let branchesHtml = '';
  algo.branches.forEach(branch => {
    let stepsHtml = '';
    branch.steps.forEach((step, idx) => {
      let chipsHtml = '';
      if (step.chips && step.chips.length > 0) {
        chipsHtml = `<div class="step-chips">` + step.chips.map(c => `<span class="flow-chip" onclick="quickSearch('${c}')">${c}</span>`).join('') + `</div>`;
      }
      
      const cardHtml = `
        <div class="step-card ${step.type}-choice">
          <div class="step-pill ${step.type}">${step.pill}</div>
          <div class="step-drug">${step.drug}</div>
          <div class="step-rationale">${step.rationale}</div>
          ${chipsHtml}
        </div>`;
      
      if (idx > 0) {
        stepsHtml += `<div class="step-arrow">➔</div>` + cardHtml;
      } else {
        stepsHtml += cardHtml;
      }
    });

    branchesHtml += `
      <div class="decision-branch">
        <div class="branch-condition-header">
          <span class="branch-icon">🔀</span>
          <span class="branch-cond-label">［${branch.condLabel}］</span>
          <span class="branch-target">${branch.target}</span>
        </div>
        <div class="branch-flow-steps">
          ${stepsHtml}
        </div>
      </div>`;
  });

  return `
      <!-- 📊 ガイドライン第一選択・条件分岐アルゴリズムフローチャート -->
      <div class="algo-flow-container">
        <div class="algo-header">
          <div class="algo-title-group">
            <span class="algo-tag">Clinical Flowchart</span>
            <h3 class="algo-title">📊 ${algo.title} 第一選択・条件分岐アルゴリズム</h3>
          </div>
          <span class="algo-goal-badge">🎯 目標：${algo.goal}</span>
        </div>
        <div class="decision-tree-grid">
          ${branchesHtml}
        </div>
        <div class="algo-footer-pitfall">
          <strong>⚠️ 処方監査・重要チェック：</strong>
          <span>${algo.pitfall}</span>
        </div>
      </div>
`;
}

// src/03_guide.html の置換処理
let guideHtml = fs.readFileSync('src/03_guide.html', 'utf8');

for (let i = 1; i <= 16; i++) {
  const id = 'c' + i;
  const algo = DISEASE_ALGOS[id];
  if (!algo) {
    console.error(`No algo defined for ${id}`);
    continue;
  }

  const cardStart = guideHtml.indexOf(`id="${id}"`);
  if (cardStart === -1) {
    console.error(`Card ${id} not found in guideHtml`);
    continue;
  }

  // 既存の algo-flow-container を探す
  const algoStart = guideHtml.indexOf('<div class="algo-flow-container">', cardStart);
  if (algoStart === -1) {
    console.error(`algo-flow-container not found in ${id}`);
    continue;
  }

  // そのコンテナの終了タグを探す
  // 次の <div class="grid-2"> の直前まで
  const grid2Start = guideHtml.indexOf('<div class="grid-2">', algoStart);
  if (grid2Start === -1) {
    console.error(`grid-2 not found after algo in ${id}`);
    continue;
  }

  const newAlgoHtml = generateAlgoHtml(id, algo);

  // 置換
  guideHtml = guideHtml.substring(0, algoStart) + newAlgoHtml + '\n    ' + guideHtml.substring(grid2Start);
  console.log(`Updated ${id} algorithm flowchart successfully.`);
}

